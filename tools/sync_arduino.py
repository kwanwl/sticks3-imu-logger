#!/usr/bin/env python3
"""Copy the shared firmware sources into the Arduino sketch folder.

The ESP-IDF project in main/ is the single source of truth. The Arduino IDE can only
compile files inside the sketch folder and cannot embed a file into the firmware, so this
script:
  1. copies app.h, imu.cpp, net.cpp, main.cpp and usb.cpp from main/ to arduino/sticks3_imu_logger/,
  2. copies partitions.csv (same flash layout as the ESP-IDF build),
  3. turns main/web/index.html into index_html.h (one string constant, INDEX_HTML).

Run it after changing anything in main/ or partitions.csv, then commit the results:
    python3 tools/sync_arduino.py          # update the sketch folder
    python3 tools/sync_arduino.py --check  # exit 1 if the sketch folder is out of date
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "main"
SKETCH = ROOT / "arduino" / "sticks3_imu_logger"

COPIED = ["app.h", "imu.cpp", "net.cpp", "main.cpp", "usb.cpp"]
DELIM = "html_page"  # raw-string delimiter; must not occur in index.html as ')html_page"'


def notice(name: str) -> str:
    return (f"// GENERATED by tools/sync_arduino.py from {name} - do not edit here;\n"
            f"// edit the file in main/ and run the script again.\n")


def expected_files() -> dict:
    files = {}
    for name in COPIED:
        files[name] = notice(f"main/{name}") + (SRC / name).read_text(encoding="utf-8")
    files["partitions.csv"] = (ROOT / "partitions.csv").read_text(encoding="utf-8")
    html = (SRC / "web" / "index.html").read_text(encoding="utf-8")
    if f"){DELIM}\"" in html:
        sys.exit(f"index.html contains ){DELIM}\" - choose another DELIM in sync_arduino.py")
    files["index_html.h"] = (notice("main/web/index.html") + "#pragma once\n"
                             f'static const char INDEX_HTML[] = R"{DELIM}({html}){DELIM}";\n')
    return files


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in expected_files().items():
        path = SKETCH / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8")
    if check:
        if stale:
            print("Arduino sketch out of date:", ", ".join(stale))
            print("Run: python3 tools/sync_arduino.py")
            return 1
        print("Arduino sketch is up to date")
        return 0
    print("Updated:", ", ".join(stale) if stale else "nothing (already up to date)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
